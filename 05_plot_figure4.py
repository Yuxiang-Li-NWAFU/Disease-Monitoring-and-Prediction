import os
import math
import glob

import matplotlib

matplotlib.use("Agg")

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

SCRIPT_DIR = os.path.dirname(
    os.path.abspath(__file__)
)

RESULTS_DIR = os.path.join(SCRIPT_DIR, "results")
TABLE_CANDIDATES = list(
    glob.glob(
        os.path.join(RESULTS_DIR, "model_comparison_*", "by_metric", "Table_S12_generated.xlsx")
    )
)
FILE_PATH = max(TABLE_CANDIDATES, key=os.path.getmtime) if TABLE_CANDIDATES else os.path.join(RESULTS_DIR, "Table_S12_generated.xlsx")

SHEET_NAME = "Sheet1"

FIGURE_DIR = os.path.join(RESULTS_DIR, "figures")
os.makedirs(FIGURE_DIR, exist_ok=True)
OUTPUT_PNG = os.path.join(FIGURE_DIR, "Fig_4_performance_7panels.png")

OUTPUT_PDF = os.path.join(FIGURE_DIR, "Fig_4_performance_7panels.pdf")

DPI = 600

if not os.path.exists(FILE_PATH):

    raise FileNotFoundError(
        "\nTable_S12_generated.xlsx was not found!\n"
        f"Attempted path:\n{FILE_PATH}\n\n"
        "Ensure that the Table S12 workbook has been generated by the model-training script."
    )

df = pd.read_excel(
    FILE_PATH,
    sheet_name=SHEET_NAME,
    header=1
)

required_columns = [

    "Feature selector",

    "Classifier",

    "Training Accuracy",

    "Test Accuracy",

    "Test BA",

    "Test G-mean",

    "Test F1-score",

    "Test Recall",

    "Test ROC-AUC",

    "Generalisation gap"
]

missing_columns = [

    col

    for col in required_columns

    if col not in df.columns
]

if missing_columns:

    raise ValueError(
        "\nThe Excel workbook is missing the following required columns:\n"
        +
        "\n".join(missing_columns)
    )

df = df[
    df["Feature selector"].notna()
    &
    df["Classifier"].notna()
].copy()

df["Feature selector"] = (
    df["Feature selector"]
    .astype(str)
    .str.strip()
)

df["Classifier"] = (
    df["Classifier"]
    .astype(str)
    .str.strip()
)

df["Model"] = (
    df["Feature selector"]
    +
    "+"
    +
    df["Classifier"]
)

MODEL_ORDER = [

    "RF+DT",

    "RF+LGB",

    "RF+MLP",

    "RF+RF",

    "RF+SVM",

    "RF+XGB",

    "RFE+DT",

    "RFE+LGB",

    "RFE+MLP",

    "RFE+RF",

    "RFE+SVM",

    "RFE+XGB"
]

MODEL_ORDER = [

    model

    for model in MODEL_ORDER

    if model in df["Model"].values
]

df["Model"] = pd.Categorical(
    df["Model"],
    categories=MODEL_ORDER,
    ordered=True
)

df = (
    df
    .sort_values("Model")
    .reset_index(drop=True)
)

models = (
    df["Model"]
    .astype(str)
    .values
)

numeric_columns = [

    "Training Accuracy",

    "Test Accuracy",

    "Test BA",

    "Test G-mean",

    "Test F1-score",

    "Test Recall",

    "Test ROC-AUC",

    "Generalisation gap"
]

for col in numeric_columns:

    df[col] = pd.to_numeric(
        df[col],
        errors="coerce"
    )

METRIC_SPECS = [

    (
        "A",
        "Accuracy",
        "Test Accuracy"
    ),

    (
        "B",
        "Balanced Accuracy",
        "Test BA"
    ),

    (
        "C",
        "G-mean",
        "Test G-mean"
    ),

    (
        "D",
        "F1-score",
        "Test F1-score"
    ),

    (
        "E",
        "Recall",
        "Test Recall"
    ),

    (
        "F",
        "ROC-AUC",
        "Test ROC-AUC"
    )
]

plt.rcParams["font.family"] = "Arial"

plt.rcParams["font.size"] = 10

plt.rcParams["axes.titlesize"] = 14

plt.rcParams["axes.labelsize"] = 10

plt.rcParams["xtick.labelsize"] = 7

plt.rcParams["ytick.labelsize"] = 9

plt.rcParams["legend.fontsize"] = 6

plt.rcParams["axes.linewidth"] = 0.8

color_palette = plt.cm.Set3(
    np.linspace(
        0,
        1,
        len(models)
    )
)

fig = plt.figure(
    figsize=(18, 9.6)
)

gs = fig.add_gridspec(

    nrows=2,
    ncols=4,

    left=0.055,
    right=0.985,

    bottom=0.105,
    top=0.945,

    wspace=0.32,
    hspace=0.46
)

ax_A = fig.add_subplot(
    gs[0, 0]
)

ax_B = fig.add_subplot(
    gs[0, 1]
)

ax_C = fig.add_subplot(
    gs[0, 2]
)

ax_D = fig.add_subplot(
    gs[0, 3]
)

ax_E = fig.add_subplot(
    gs[1, 0]
)

ax_F = fig.add_subplot(
    gs[1, 1]
)

ax_G = fig.add_subplot(
    gs[1, 2]
)

ax_blank = fig.add_subplot(
    gs[1, 3]
)

ax_blank.axis("off")

all_axes = [

    ax_A,

    ax_B,

    ax_C,

    ax_D,

    ax_E,

    ax_F,

    ax_G
]

for ax in all_axes:

    ax.set_box_aspect(1)

metric_axes = [

    ax_A,

    ax_B,

    ax_C,

    ax_D,

    ax_E,

    ax_F
]

x = np.arange(
    len(models)
)

for ax, (
    panel_letter,
    title,
    column_name
) in zip(
    metric_axes,
    METRIC_SPECS
):

    values = pd.to_numeric(
        df[column_name],
        errors="coerce"
    ).values

    bars = ax.bar(

        x,

        values,

        color=color_palette,

        edgecolor="black",

        linewidth=0.55,

        width=0.76
    )

    for bar, value in zip(
        bars,
        values
    ):

        if not np.isfinite(value):
            continue

        if (
            title == "Recall"
            and
            np.isclose(
                value,
                1.0
            )
        ):

            text_y = 1.012

            vertical_alignment = "bottom"

        else:

            text_y = (
                value
                +
                0.012
            )

            vertical_alignment = "bottom"

        ax.text(

            bar.get_x()
            +
            bar.get_width() / 2,

            text_y,

            f"{value:.3f}",

            ha="center",

            va=vertical_alignment,

            fontsize=6.5,

            fontweight="bold",

            clip_on=False
        )

    ax.set_title(

        title,

        fontsize=14,

        fontweight="bold",

        pad=9
    )

    ax.set_ylabel(
        "Score",
        fontsize=10
    )

    ax.set_ylim(
        0,
        1.0
    )

    ax.set_yticks(
        np.arange(
            0,
            1.01,
            0.2
        )
    )

    ax.set_xticks(
        x
    )

    ax.set_xticklabels(

        models,

        rotation=45,

        ha="right",

        rotation_mode="anchor",

        fontsize=7
    )

    ax.grid(

        axis="y",

        linestyle="--",

        linewidth=0.7,

        alpha=0.40
    )

    ax.set_axisbelow(
        True
    )

    ax.text(

        -0.14,

        1.07,

        panel_letter,

        transform=ax.transAxes,

        fontsize=18,

        fontweight="bold",

        ha="left",

        va="top",

        clip_on=False
    )

training_accuracy = (
    df["Training Accuracy"]
    .values
    *
    100
)

test_accuracy = (
    df["Test Accuracy"]
    .values
    *
    100
)

for i, (
    train_acc,
    test_acc
) in enumerate(
    zip(
        training_accuracy,
        test_accuracy
    )
):

    if (
        not np.isfinite(train_acc)
        or
        not np.isfinite(test_acc)
    ):

        continue

    ax_G.scatter(

        train_acc,

        test_acc,

        s=85,

        color=color_palette[i],

        edgecolor="black",

        linewidth=0.55,

        label=models[i],

        zorder=3
    )

valid_accuracy_values = np.concatenate(
    [
        training_accuracy[
            np.isfinite(
                training_accuracy
            )
        ],

        test_accuracy[
            np.isfinite(
                test_accuracy
            )
        ]
    ]
)

if len(valid_accuracy_values) == 0:

    lower_limit = 70

else:

    min_accuracy = np.min(
        valid_accuracy_values
    )

    lower_limit = (
        math.floor(
            (
                min_accuracy
                -
                3
            )
            /
            5
        )
        *
        5
    )

lower_limit = max(
    0,
    lower_limit
)

upper_limit = 100

if lower_limit >= upper_limit:

    lower_limit = 70

ax_G.plot(

    [
        lower_limit,
        upper_limit
    ],

    [
        lower_limit,
        upper_limit
    ],

    linestyle="--",

    linewidth=1.3,

    color="black",

    alpha=0.70,

    zorder=1
)

ax_G.set_xlim(
    lower_limit,
    upper_limit
)

ax_G.set_ylim(
    lower_limit,
    upper_limit
)

ax_G.set_aspect(
    "equal",
    adjustable="box"
)

g_ticks = np.arange(

    math.ceil(
        lower_limit
        /
        5
    )
    *
    5,

    101,

    5
)

ax_G.set_xticks(
    g_ticks
)

ax_G.set_yticks(
    g_ticks
)

ax_G.set_xlabel(

    "Training Accuracy (%)",

    fontsize=10,

    fontweight="bold"
)

ax_G.set_ylabel(

    "Test Accuracy (%)",

    fontsize=10,

    fontweight="bold"
)

ax_G.set_title(

    "Generalisation Gap",

    fontsize=14,

    fontweight="bold",

    pad=9
)

ax_G.grid(

    linestyle="--",

    linewidth=0.7,

    alpha=0.40
)

ax_G.set_axisbelow(
    True
)

ax_G.text(

    -0.14,

    1.07,

    "G",

    transform=ax_G.transAxes,

    fontsize=18,

    fontweight="bold",

    ha="left",

    va="top",

    clip_on=False
)

ax_G.legend(

    loc="upper left",

    ncol=2,

    fontsize=5.5,

    frameon=True,

    columnspacing=0.6,

    handletextpad=0.25,

    borderpad=0.35,

    labelspacing=0.30,

    markerscale=0.75
)

for ax in all_axes:

    for spine in ax.spines.values():

        spine.set_linewidth(
            0.8
        )

try:

    output_dir = os.path.dirname(
        OUTPUT_PNG
    )

    os.makedirs(
        output_dir,
        exist_ok=True
    )

    fig.savefig(

        OUTPUT_PNG,

        dpi=DPI,

        bbox_inches="tight",

        facecolor="white"
    )

    fig.savefig(

        OUTPUT_PDF,

        bbox_inches="tight",

        facecolor="white"
    )

except Exception as e:

    

    print(
        " Failed to save figures"
    )

    print(
        f"Error details: {e}"
    )

    

    

    raise

print(f"Figure 4 saved to {OUTPUT_PNG} and {OUTPUT_PDF}")

plt.close(fig)
